pub fn find_nearest_city(lat: f64, lon: f64) -> Option<(&'static str, &'static str)> {
    if lat == 0.0 && lon == 0.0 {
        return None;
    }
    let lat_rad = lat.to_radians();
    let lon_rad = lon.to_radians();
    CITIES
        .iter()
        .map(|&(city, country, clat, clon)| {
            let clat_rad = clat.to_radians();
            let clon_rad = clon.to_radians();
            let dlat = clat_rad - lat_rad;
            let dlon = clon_rad - lon_rad;
            let a = (dlat / 2.0).sin().powi(2)
                + lat_rad.cos() * clat_rad.cos() * (dlon / 2.0).sin().powi(2);
            let c = 2.0 * a.sqrt().asin();
            let dist = 6371.0 * c;
            (city, country, dist)
        })
        .min_by(|a, b| a.2.partial_cmp(&b.2).unwrap_or(std::cmp::Ordering::Equal))
        .filter(|&(_, _, dist)| dist < 200.0)
        .map(|(city, country, _)| (city, country))
}

